async def trigger_simulated_bids_for_ride(ride_id: str):
    """Generates 2 to 3 simulated captain counter bids with natural delays."""
    if not store.simulator_active:
        return

    ride = store.get_ride(ride_id)
    if not ride:
        return

    # Select 2-3 random captains
    num_bids = random.randint(2, 3)
    selected_captains = random.sample(BOT_CAPTAINS, num_bids)

    base_offer = ride["passenger_offer"]

    for index, captain in enumerate(selected_captains):
        # Wait between 2.5 and 5 seconds for each bid
        delay = random.uniform(2.5, 5.0)
        await asyncio.sleep(delay)

        # Check if ride is still open/bidding
        current_ride = store.get_ride(ride_id)
        if not current_ride or current_ride["status"] not in ["OPEN", "BIDDING"]:
            break

        # Calculate a realistic counter offer (e.g. -5% to +15% of passenger offer)
        factor = random.choice([0.95, 1.0, 1.05, 1.10, 1.15])
        bid_amount = int(round((base_offer * factor) / 50.0) * 50) # round to nearest 50 PKR
        
        distance_away = round(random.uniform(1.2, 5.5), 1)
        eta_mins = random.randint(3, 12)

        bid = store.add_bid(
            ride_id=ride_id,
            captain_name=captain["name"],
            captain_avatar=captain["avatar"],
            phone=captain["phone"],
            vehicle=captain["vehicle"],
            rating=captain["rating"],
            trips_count=captain["trips"],
            amount=bid_amount,
            eta_mins=eta_mins,
            distance_km=distance_away
        )

        if bid:
            logger.info(f"Simulated bid generated by {captain['name']} for {ride_id}: PKR {bid_amount}")
            # Broadcast live update over WebSocket
            await manager.broadcast({
                "type": "BID_RECEIVED",
                "ride_id": ride_id,
                "bid": bid,
                "all_bids": store.get_ride(ride_id)["bids"],
                "ride": store.get_ride(ride_id)
            })

async def simulate_ride_progress(ride_id: str):
    """Simulates driver en-route, trip start, and trip completion sequence."""
    statuses = ["EN_ROUTE", "TRIP_STARTED", "COMPLETED"]
    delays = [4, 8, 12]

    for status, delay in zip(statuses, delays):
        await asyncio.sleep(delay)
        updated_ride = store.update_status(ride_id, status)
        if updated_ride:
            await manager.broadcast({
                "type": "RIDE_STATUS_UPDATED",
                "ride_id": ride_id,
                "status": status,
                "ride": updated_ride
            })
